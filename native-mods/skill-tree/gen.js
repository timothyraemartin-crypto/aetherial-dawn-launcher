// Generates src/tree_data.h from data/skills-catalog.json: which of our skills sits on which vanilla constellation,
// and which of our perks goes on which star order. Run: node gen.js
const fs = require('fs');
const cat = require('./data/skills-catalog.json');

// Unique perk stars per vanilla skill AV (from the in-game probe log, data/probe-log-vanilla-layout.log).
const STARS = { 6: 10, 7: 9, 8: 9, 9: 9, 10: 10, 11: 8, 12: 6, 13: 8, 14: 11, 15: 9, 16: 9, 17: 9, 18: 10, 19: 15, 20: 14, 21: 13, 22: 12, 23: 9 };
const AVNAME = { 6: 'OneHanded', 7: 'TwoHanded', 8: 'Marksman', 9: 'Block', 10: 'Smithing', 11: 'HeavyArmor', 12: 'LightArmor', 13: 'Pickpocket', 14: 'Lockpicking', 15: 'Sneak', 16: 'Alchemy', 17: 'Speechcraft', 18: 'Alteration', 19: 'Conjuration', 20: 'Destruction', 21: 'Illusion', 22: 'Restoration', 23: 'Enchanting' };
const PIN = { blacksmithing: 10, alchemy: 16 }; // the Lab's existing vanilla sync already drives these two
const skills = [];
for (const sec of cat.sections) for (const s of sec.skills) skills.push(Object.assign({ section: sec.id }, s));

// largest trees on the largest constellations
const free = Object.keys(STARS).map(Number).filter((av) => !Object.values(PIN).includes(av)).sort((a, b) => STARS[b] - STARS[a] || a - b);
const rest = skills.filter((s) => !(s.id in PIN)).sort((a, b) => b.tree.length - a.tree.length || a.id.localeCompare(b.id));
const avOf = Object.assign({}, PIN);
rest.forEach((s, i) => { avOf[s.id] = free[i]; });

function trim(tree, max) {
  let t = tree.slice();
  const needed = (p) => t.some((q) => q.requires.includes(p.id));
  while (t.length > max) {
    // drop a low-tier "improve" leaf nobody requires (capstones last); else any leaf
    const leaves = t.filter((p) => !needed(p) && !p.base);
    let pool = leaves.filter((p) => p.kind === 'improve');
    if (!pool.length) pool = leaves;
    pool.sort((a, b) => (a.tier === 5) - (b.tier === 5) || a.tier - b.tier || b.col - a.col);
    t = t.filter((p) => p !== pool[0]);
  }
  return t;
}
const esc = (str) => { let o = ''; for (const b of Buffer.from(String(str), 'utf8')) { if (b === 34 || b === 92) o += '\\' + String.fromCharCode(b); else if (b >= 32 && b < 127) o += String.fromCharCode(b); else o += '\\' + b.toString(8).padStart(3, '0'); } return o; };

let h = '// GENERATED by gen.js from skills-catalog.json. Do not edit.\n#pragma once\n#include <cstdint>\nstruct TPerk { const char* id; const char* name; const char* desc; int tier; int col; };\nstruct TSkill { const char* id; const char* name; const char* desc; int av; int stars; int nperks; const TPerk* perks; int nextra; const TPerk* extra; };\n';
const report = [];
const out = [];
for (const s of skills) {
  const av = avOf[s.id], stars = STARS[av];
  const kept = trim(s.tree, stars).sort((a, b) => a.tier - b.tier || a.col - b.col);
  const dropped = s.tree.filter((p) => !kept.includes(p)).map((p) => p.id);
  report.push({ skill: s.id, av: AVNAME[av] + '(' + av + ')', stars, ours: s.tree.length, shown: kept.length, dropped });
  const nm = 'P_' + s.id;
  h += `static const TPerk ${nm}[] = {\n` + kept.map((p) => `  {"${esc(p.id)}","${esc(p.name)}","${esc((p.kind === 'access' ? 'Unlocks: ' : '') + p.desc)}",${p.tier},${p.col}},`).join('\n') + '\n};\n';
  // perks with no star in the vanilla sky: the DLL names them in the skill's description once the player has them
  const xs = s.tree.filter((p) => !kept.includes(p));
  if (xs.length) h += `static const TPerk X_${s.id}[] = {\n` + xs.map((p) => `  {"${esc(p.id)}","${esc(p.name)}","",${p.tier},${p.col}},`).join('\n') + '\n};\n';
  out.push(`  {"${s.id}","${esc(s.name)}","${esc(s.desc)}",${av},${stars},${kept.length},${nm},${xs.length},${xs.length ? 'X_' + s.id : 'nullptr'}},`);
}
h += 'static const TSkill kSkills[] = {\n' + out.join('\n') + '\n};\nstatic const int kSkillCount = ' + skills.length + ';\n';
fs.writeFileSync('src/tree_data.h', h);
fs.writeFileSync('data/assignment-report.json', JSON.stringify(report, null, 1));
console.log(report.map((r) => `${r.skill.padEnd(15)} -> ${r.av.padEnd(16)} stars ${r.stars} ours ${r.ours} shown ${r.shown}${r.dropped.length ? ' dropped ' + r.dropped.join(',') : ''}`).join('\n'));
console.log('total dropped', report.reduce((a, r) => a + r.dropped.length, 0));
